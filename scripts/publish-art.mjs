#!/usr/bin/env node
/**
 * Publishes .art-out/ to GitHub release assets (art-0 … art-7). Only files that are not already
 * uploaded are sent, so repeat builds upload little. Needs GH_TOKEN with contents: write in CI.
 */
import { execFileSync } from "node:child_process";
import { readdirSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { artTag, ART_REPO, ART_SHARDS } from "./artwork/art-hosting.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = resolve(ROOT, ".art-out");
const gh = (args, opts = {}) => execFileSync("gh", args, { encoding: "utf8", maxBuffer: 1 << 28, ...opts });

if (!existsSync(DIR)) { console.log("no .art-out directory, nothing to publish"); process.exit(0); }
const files = readdirSync(DIR).filter((f) => f.endsWith(".webp"));
console.log(`${files.length} artwork files to check`);

let uploaded = 0, failed = 0;
for (let shard = 0; shard < ART_SHARDS; shard++) {
  const tag = `art-${shard}`;
  const mine = files.filter((f) => artTag(f) === tag);
  if (!mine.length) continue;
  try {
    gh(["release", "view", tag, "--repo", ART_REPO, "--json", "tagName"]);
  } catch {
    gh(["release", "create", tag, "--repo", ART_REPO, "--title", `Re:Port artwork ${tag}`,
      "--notes", "Build-time catalog artwork (covers, heroes, screenshots). Generated by CI; not a port release.",
      "--latest=false"]);
  }
  const existing = new Set(JSON.parse(gh(["release", "view", tag, "--repo", ART_REPO, "--json", "assets"])).assets.map((a) => a.name));
  const todo = mine.filter((f) => !existing.has(f));
  console.log(`${tag}: ${mine.length} files, ${todo.length} to upload`);
  for (let i = 0; i < todo.length; i += 25) {
    const batch = todo.slice(i, i + 25).map((f) => resolve(DIR, f));
    try {
      gh(["release", "upload", tag, "--repo", ART_REPO, ...batch]);
      uploaded += batch.length;
    } catch (err) {
      failed += batch.length;
      console.error(`${tag}: batch failed: ${err.message.split("\n")[0]}`);
    }
  }
}
console.log(`uploaded ${uploaded}, failed ${failed}`);
if (failed) process.exitCode = 1;
