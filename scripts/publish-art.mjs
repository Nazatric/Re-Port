#!/usr/bin/env node
/**
 * Publishes .art-out/ to GitHub release assets (art-0 … art-7). Only files that are not already
 * uploaded are sent, so every build finishes what the previous one could not. Needs GH_TOKEN with
 * contents: write in CI.
 *
 * GitHub rate-limits asset uploads (secondary limit, "HTTP 403: API rate limit exceeded"). When that
 * happens the upload waits and retries; a shard that cannot finish in this run is left for the next run
 * instead of aborting the others. A time budget keeps the step from running past its timeout.
 */
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { readdirSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { artTag, ART_REPO, ART_SHARDS } from "./artwork/art-hosting.mjs";

const run = promisify(execFile);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = resolve(ROOT, ".art-out");
const BUDGET_MS = Number(process.env.PUBLISH_BUDGET_MS || 30 * 60 * 1000);
const started = Date.now();
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function gh(args) {
  return (await run("gh", args, { maxBuffer: 1 << 28 })).stdout;
}

/** Runs a gh call, retrying with backoff on rate limits and transient server errors. */
async function ghRetry(args, label) {
  let wait = 30000;
  for (let attempt = 1; ; attempt++) {
    try {
      return await gh(args);
    } catch (err) {
      const msg = String(err.stderr || err.message);
      const retryable = /rate limit|secondary|HTTP 40[39]|HTTP 5\d\d|timed out|EAI_AGAIN|ECONNRESET/i.test(msg);
      if (!retryable || attempt >= 8 || Date.now() - started > BUDGET_MS) throw new Error(`${label}: ${msg.split("\n")[0]}`);
      await sleep(wait);
      wait = Math.min(wait * 2, 5 * 60 * 1000);
    }
  }
}

if (!existsSync(DIR)) { console.log("no .art-out directory, nothing to publish"); process.exit(0); }
const files = readdirSync(DIR).filter((f) => f.endsWith(".webp"));
console.log(`${files.length} artwork files in .art-out`);

let uploaded = 0, skipped = 0, failed = 0;
for (let shard = 0; shard < ART_SHARDS; shard++) {
  const tag = `art-${shard}`;
  const mine = files.filter((f) => artTag(f) === tag);
  if (!mine.length) continue;
  if (Date.now() - started > BUDGET_MS) { console.log(`${tag}: time budget reached, left for the next run`); failed += mine.length; continue; }
  try {
    await ghRetry(["release", "view", tag, "--repo", ART_REPO, "--json", "tagName"], `${tag} view`).catch(async () => {
      await ghRetry(["release", "create", tag, "--repo", ART_REPO, "--title", `Re:Port artwork ${tag}`,
        "--notes", "Build-time catalog artwork (covers, heroes, screenshots). Generated by CI; not a port release.",
        "--latest=false"], `${tag} create`);
    });
    const existing = new Set(JSON.parse(await ghRetry(["release", "view", tag, "--repo", ART_REPO, "--json", "assets"], `${tag} assets`)).assets.map((a) => a.name));
    const todo = mine.filter((f) => !existing.has(f));
    skipped += mine.length - todo.length;
    console.log(`${tag}: ${mine.length} files, ${todo.length} to upload`);
    for (const f of todo) {
      if (Date.now() - started > BUDGET_MS) { failed++; continue; }
      try {
        await ghRetry(["release", "upload", tag, "--repo", ART_REPO, resolve(DIR, f)], `${tag} upload ${f}`);
        uploaded++;
      } catch (err) {
        failed++;
        console.error(err.message);
      }
    }
  } catch (err) {
    failed += mine.length;
    console.error(`${tag}: ${err.message}`);
  }
}
console.log(`uploaded ${uploaded}, already present ${skipped}, still missing ${failed}`);
// Failures are not fatal: the next build retries whatever is missing.
