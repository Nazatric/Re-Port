const INDEX: Record<Exclude<LangCode, "en">, number> = { es: 0, pt: 1, hi: 2, zh: 3 };

/** Returns a translator for the language. Use the English text as the key; `{name}` placeholders are filled from `vars`. */
export function makeT(lang: LangCode) {
  return (key: string, vars?: Record<string, string | number>): string => {
    let text = key;
    if (lang !== "en") {
      const entry = DICT[key];
      if (entry) text = entry[INDEX[lang]] || key;
    }
    if (vars) for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
    return text;
  };
}

// Module-level translator for code that runs outside React render (labels, toasts, constants).
// AppProvider calls setLanguage() on every render, so the current language is always in sync.
let currentLanguage: LangCode = "en";
export function setLanguage(lang: LangCode) {
  currentLanguage = lang;
}
export function t(key: string, vars?: Record<string, string | number>): string {
  return makeT(currentLanguage)(key, vars);
}

